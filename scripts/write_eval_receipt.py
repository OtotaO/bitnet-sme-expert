#!/usr/bin/env python3
"""Inject a dated per-domain score table into the README between markers.

Mechanism only — this script *never* invents numbers. It reads the JSON
receipts that ``scripts/optimize.py`` writes under ``eval/receipts/`` and renders
them as a Markdown table between the ``EVAL_RECEIPT`` markers in ``README.md``.

If no receipt JSON files exist, it writes a clearly-labelled placeholder rather
than fabricating a result. Run it after a real optimizer run produces a receipt:

    python scripts/optimize.py --domain math --optimizer miprov2 --auto light
    python scripts/write_eval_receipt.py        # or: make eval-receipt

Each receipt is expected to look like ``eval/receipts/<domain>-<optimizer>.json``
with at least: ``domain``, ``optimizer``, ``lm``, ``baseline``, ``optimized``,
``delta``, ``n_holdout``. Missing keys are rendered as ``?`` (never guessed).

Exit status:
* 0 — README updated (or already up to date)
* 1 — markers not found in README (mechanism not wired)
* 2 — invocation / IO error
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RECEIPTS_DIR = REPO_ROOT / "eval" / "receipts"
README = REPO_ROOT / "README.md"

BEGIN = "<!-- BEGIN:EVAL_RECEIPT -->"
END = "<!-- END:EVAL_RECEIPT -->"

PLACEHOLDER = (
    "_No machine-generated receipt table yet. Run `scripts/optimize.py` with a\n"
    "provider key to produce `eval/receipts/<domain>-<optimizer>.json`, then\n"
    "`make eval-receipt` to fill this in. (Placeholder — no measured numbers.)_"
)


def _fmt(value: object) -> str:
    """Render a metric cell, never inventing a value for a missing key."""
    if value is None:
        return "?"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def _load_receipts(receipts_dir: Path) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for path in sorted(receipts_dir.glob("*.json")):
        try:
            data = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError) as exc:
            print(f"warning: skipping unreadable receipt {path.name}: {exc}", file=sys.stderr)
            continue
        if isinstance(data, dict):
            data["_file"] = path.name
            rows.append(data)
    return rows


def render_block(receipts: list[dict[str, object]], stamp: str) -> str:
    """Build the marker block body from real receipts (or a placeholder)."""
    if not receipts:
        return PLACEHOLDER

    header = (
        f"Generated by `scripts/write_eval_receipt.py` on {stamp} from "
        f"`eval/receipts/`. Numbers are copied verbatim from the JSON receipts; "
        f"this table never invents values.\n\n"
        "| Domain | Optimizer | LM | Baseline | Optimized | Delta | N (holdout) | Receipt |\n"
        "| --- | --- | --- | ---: | ---: | ---: | ---: | --- |"
    )
    lines = [header]
    for r in receipts:
        lines.append(
            "| {domain} | {optimizer} | {lm} | {baseline} | {optimized} | "
            "{delta} | {n} | `{file}` |".format(
                domain=_fmt(r.get("domain")),
                optimizer=_fmt(r.get("optimizer")),
                lm=_fmt(r.get("lm")),
                baseline=_fmt(r.get("baseline")),
                optimized=_fmt(r.get("optimized")),
                delta=_fmt(r.get("delta")),
                n=_fmt(r.get("n_holdout")),
                file=_fmt(r.get("_file")),
            )
        )
    return "\n".join(lines)


def inject(readme_text: str, block_body: str) -> str:
    begin_idx = readme_text.find(BEGIN)
    end_idx = readme_text.find(END)
    if begin_idx == -1 or end_idx == -1 or end_idx < begin_idx:
        raise LookupError(f"markers {BEGIN} / {END} not found (or out of order) in README")
    head = readme_text[: begin_idx + len(BEGIN)]
    tail = readme_text[end_idx:]
    return f"{head}\n{block_body}\n{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--readme", type=Path, default=README)
    parser.add_argument("--receipts-dir", type=Path, default=RECEIPTS_DIR)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the README would change (CI drift gate).",
    )
    args = parser.parse_args(argv)

    try:
        readme_text = args.readme.read_text()
    except OSError as exc:
        print(f"error: cannot read {args.readme}: {exc}", file=sys.stderr)
        return 2

    receipts = _load_receipts(args.receipts_dir)
    stamp = _dt.date.today().isoformat()
    block_body = render_block(receipts, stamp)

    try:
        updated = inject(readme_text, block_body)
    except LookupError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if updated == readme_text:
        print("README eval-receipt block already up to date.")
        return 0

    if args.check:
        print(
            "README eval-receipt block is stale; run scripts/write_eval_receipt.py", file=sys.stderr
        )
        return 1

    args.readme.write_text(updated)
    n = len(receipts)
    print(f"Updated {args.readme} eval-receipt block from {n} receipt(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
